from typing import Union

from ._specialConstants import SpecialConstants


class PDGCodes(SpecialConstants):
	_pdgCodes = {}
	_names = {}
	def __init__(self) -> None:
		super().__init__()
		PDGCodes._names = { pdgCode: name for name, pdgCode in PDGCodes._pdgCodes.items() }

	@classmethod
	def getPDGCode(cls, nameOrCode: Union[str,int]) -> int:
		if isinstance(nameOrCode, int):
			return nameOrCode
		if nameOrCode in cls._pdgCodes:
			return cls._pdgCodes[nameOrCode]
		raise LookupError(f"Cannot find particle '{nameOrCode}' in PDGCodes!")

	@classmethod
	def getName(cls, pdgCode: int) -> str:
		return cls._names[cls.getPDGCode(pdgCode)]

	def __getitem__(self, name: Union[str,int]) -> Union[str,int]:
		"""Return the particle name if a PDG code (int) is given or the PDG code if a particle name (str) is given.

		Returns None if the `name` could not be found (in contrast to getName, which raises an exception).

		Args:
			name (Union[str,int]): PDG code (int) or particle name (str)

		Returns:
			Union[str,int]:  The particle name if a PDG code (int) is given or the PDG code if a particle name (str) is given
		"""
		try:
			if isinstance(name, str):
				return self.getPDGCode(name)
			return self.getName(name)
		except LookupError:
			return None

	def __contains__(self, nameOrCode: Union[str,int]) -> bool:
		if isinstance(nameOrCode, int):
			return nameOrCode in self._names
		if isinstance(nameOrCode, str):
			return nameOrCode in self._pdgCodes
		raise Exception(f"PDGCodes contains only strings (particle names) or ints (PDG codes), but is {type(nameOrCode)}")


